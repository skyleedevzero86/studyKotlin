-- =============================================================================
-- V1: 주문 행 분리
-- -----
-- 목적
-- - 같은 orders 테이블에 테넌트 행을 함께 둔다
-- - tenant_id 와 order_id 조합을 유일 키로 둔다
-- 주의
-- - Hibernate @TenantId 가 조회 조건과 저장 값을 채운다
-- - 네이티브 SQL 에는 이 조건이 자동으로 들어가지 않는다
-- =============================================================================

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(40) NOT NULL,
    order_id VARCHAR(40) NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT uq_orders_tenant_order UNIQUE (tenant_id, order_id)
);

COMMENT ON TABLE orders IS '테넌트별 주문. 한 테이블에 행으로 나눈다.';
COMMENT ON COLUMN orders.id IS '테이블 기본 키.';
COMMENT ON COLUMN orders.tenant_id IS '테넌트 식별자. Hibernate @TenantId.';
COMMENT ON COLUMN orders.order_id IS '테넌트 안에서 유일한 주문 번호.';
COMMENT ON COLUMN orders.status IS '주문 상태.';
